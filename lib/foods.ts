export type Food = { name: string; kcal: number; protein: number; carbs: number; fat: number; portion: string; grams: number };

export const FOODS: Food[] = ROWS.map(([name, kcal, protein, carbs, fat, portion, grams]) => ({ name, kcal, protein, carbs, fat, portion, grams }));

// Nutrients for a quantity in grams.
export function forGrams(f: Pick<Food, 'kcal' | 'protein' | 'carbs' | 'fat'>, grams: number) {
  const k = grams / 100;
  const r = (n: number) => Math.round(n * k * 10) / 10;
  return { calories: Math.round(f.kcal * k), protein_g: r(f.protein), carbs_g: r(f.carbs), fat_g: r(f.fat) };
}
